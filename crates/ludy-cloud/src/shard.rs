//! Content-defined shards and manifests, shared by the server and the client.
//!
//! File content is cut into shards with FastCDC: the cut points depend on the
//! bytes themselves, so inserting or changing a few bytes moves only the
//! shards around the edit. A shard is named by the SHA-256 of its bytes and
//! stored once. A manifest is the ordered list of segments that make up one
//! version of a file.

use std::io::{self, Read};

use fastcdc::v2020::StreamCDC;
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

/// Shard size bounds: about 2 MiB on average.
pub const MIN_SHARD: u32 = 256 * 1024;
pub const AVG_SHARD: u32 = 2 * 1024 * 1024;
pub const MAX_SHARD: u32 = 16 * 1024 * 1024;

/// One piece of a file.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum Segment {
    /// `n` stored bytes whose SHA-256 is `h` (64 lowercase hex characters).
    Shard { h: String, n: u64 },
    /// `n` generated bytes: the synthetic stream for `seed`, from `off`.
    /// Splittable at any offset, so patching a synthetic object costs
    /// nothing for the parts that stay.
    Synth { seed: u64, off: u64, n: u64 },
}

impl Segment {
    pub fn len(&self) -> u64 {
        match self {
            Segment::Shard { n, .. } | Segment::Synth { n, .. } => *n,
        }
    }

    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }
}

/// The content of one version: its size and the segments that add up to it.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct Manifest {
    pub size: u64,
    pub segments: Vec<Segment>,
}

impl Manifest {
    /// A manifest is named by the SHA-256 of its JSON, so identical content
    /// cut the same way shares one manifest.
    pub fn id(&self) -> String {
        sha256_hex(&serde_json::to_vec(self).expect("manifest serializes"))
    }

    /// Structural checks: well-formed hashes, no empty segments, and lengths
    /// that add up to `size`.
    pub fn validate(&self) -> Result<(), String> {
        let mut total = 0u64;
        for s in &self.segments {
            if s.is_empty() {
                return Err("empty segment".into());
            }
            if let Segment::Shard { h, n } = s {
                if !valid_hash(h) {
                    return Err(format!("bad shard hash {h:?}"));
                }
                if *n > MAX_SHARD as u64 {
                    return Err(format!("shard of {n} bytes exceeds the maximum"));
                }
            }
            total = total.checked_add(s.len()).ok_or("size overflow")?;
        }
        if total != self.size {
            return Err(format!("segments add up to {total}, not {}", self.size));
        }
        Ok(())
    }

    /// Bytes of this manifest that are generated rather than stored.
    pub fn synthetic_bytes(&self) -> u64 {
        self.segments.iter().map(|s| if matches!(s, Segment::Synth { .. }) { s.len() } else { 0 }).sum()
    }

    /// Join neighbouring synthetic segments that continue each other.
    pub fn coalesce(&mut self) {
        let mut out: Vec<Segment> = Vec::with_capacity(self.segments.len());
        for s in self.segments.drain(..) {
            if let (Some(Segment::Synth { seed: a, off: ao, n: an }), Segment::Synth { seed: b, off: bo, n: bn }) = (out.last_mut(), &s) {
                if *a == *b && *ao + *an == *bo {
                    *an += *bn;
                    continue;
                }
            }
            out.push(s);
        }
        self.segments = out;
    }
}

/// Exactly 64 lowercase hex characters. Checked before a hash is ever used
/// to build a path.
pub fn valid_hash(h: &str) -> bool {
    h.len() == 64 && h.bytes().all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

pub fn sha256_hex(data: &[u8]) -> String {
    let digest = Sha256::digest(data);
    let mut out = String::with_capacity(64);
    for b in digest {
        out.push(char::from_digit((b >> 4) as u32, 16).unwrap());
        out.push(char::from_digit((b & 15) as u32, 16).unwrap());
    }
    out
}

/// One shard cut from a stream.
pub struct Chunk {
    /// Offset within the stream that was chunked.
    pub offset: u64,
    pub hash: String,
    pub data: Vec<u8>,
}

/// Cut a stream into shards. Memory use is bounded by [`MAX_SHARD`].
pub fn chunks<R: Read>(source: R) -> impl Iterator<Item = io::Result<Chunk>> {
    StreamCDC::new(source, MIN_SHARD, AVG_SHARD, MAX_SHARD).map(|c| {
        let c = c.map_err(io::Error::from)?;
        Ok(Chunk { offset: c.offset, hash: sha256_hex(&c.data), data: c.data })
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::synth;

    fn cut(data: &[u8]) -> Vec<(u64, usize, String)> {
        chunks(data).map(|c| c.unwrap()).map(|c| (c.offset, c.data.len(), c.hash)).collect()
    }

    #[test]
    fn sha256_matches_a_known_vector() {
        assert_eq!(sha256_hex(b"abc"), "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
        assert!(valid_hash(&sha256_hex(b"")));
        assert!(!valid_hash("ABC"));
        assert!(!valid_hash(&"g".repeat(64)));
        assert!(!valid_hash(&format!("../{}", "a".repeat(61))));
    }

    #[test]
    fn shards_cover_the_stream_within_the_size_bounds() {
        let data = synth::bytes(11, 0, 24 << 20);
        let shards = cut(&data);
        assert!(shards.len() >= 4, "24 MiB should give several shards, got {}", shards.len());
        let mut pos = 0u64;
        for (i, (off, n, _)) in shards.iter().enumerate() {
            assert_eq!(*off, pos);
            assert!(*n <= MAX_SHARD as usize);
            if i + 1 < shards.len() {
                assert!(*n >= MIN_SHARD as usize);
            }
            pos += *n as u64;
        }
        assert_eq!(pos, data.len() as u64);
    }

    #[test]
    fn an_edit_in_the_middle_changes_only_nearby_shards() {
        let mut data = synth::bytes(12, 0, 24 << 20);
        let before = cut(&data);
        for b in &mut data[12 << 20..(12 << 20) + 4096] {
            *b ^= 0x5a;
        }
        let after = cut(&data);
        let old: std::collections::HashSet<&String> = before.iter().map(|s| &s.2).collect();
        let fresh: Vec<_> = after.iter().filter(|s| !old.contains(&s.2)).collect();
        assert!(!fresh.is_empty());
        assert!(fresh.len() <= 3, "{} new shards for a 4 KiB edit", fresh.len());
    }

    #[test]
    fn inserting_bytes_resynchronises() {
        let data = synth::bytes(13, 0, 16 << 20);
        let before = cut(&data);
        let mut shifted = data[..1 << 20].to_vec();
        shifted.extend_from_slice(b"seventeen bytes!!");
        shifted.extend_from_slice(&data[1 << 20..]);
        let after = cut(&shifted);
        let old: std::collections::HashSet<&String> = before.iter().map(|s| &s.2).collect();
        let kept = after.iter().filter(|s| old.contains(&s.2)).count();
        assert!(kept + 3 >= after.len(), "only {kept} of {} shards survived an insert", after.len());
    }

    #[test]
    fn manifest_validation_and_identity() {
        let h = sha256_hex(b"x");
        let good = Manifest { size: 10, segments: vec![Segment::Shard { h: h.clone(), n: 4 }, Segment::Synth { seed: 1, off: 8, n: 6 }] };
        assert!(good.validate().is_ok());
        assert_eq!(good.synthetic_bytes(), 6);
        assert_eq!(good.id(), good.clone().id());
        let json = serde_json::to_string(&good).unwrap();
        assert_eq!(serde_json::from_str::<Manifest>(&json).unwrap(), good);

        let wrong_size = Manifest { size: 11, ..good.clone() };
        assert!(wrong_size.validate().is_err());
        assert_ne!(wrong_size.id(), good.id());
        let bad_hash = Manifest { size: 4, segments: vec![Segment::Shard { h: "../../etc".into(), n: 4 }] };
        assert!(bad_hash.validate().is_err());
        let empty = Manifest { size: 0, segments: vec![Segment::Shard { h, n: 0 }] };
        assert!(empty.validate().is_err());
        assert!(Manifest::default().validate().is_ok());
    }

    #[test]
    fn coalesce_joins_contiguous_synthetic_segments() {
        let mut m = Manifest {
            size: 30,
            segments: vec![
                Segment::Synth { seed: 1, off: 0, n: 10 },
                Segment::Synth { seed: 1, off: 10, n: 10 },
                Segment::Synth { seed: 1, off: 25, n: 5 },
                Segment::Synth { seed: 2, off: 30, n: 5 },
            ],
        };
        m.coalesce();
        assert_eq!(m.segments.len(), 3);
        assert_eq!(m.segments[0], Segment::Synth { seed: 1, off: 0, n: 20 });
    }
}
